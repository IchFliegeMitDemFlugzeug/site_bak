# Импортируем класс Path для удобной работы с файлами и каталогами.
from pathlib import Path


# Получаем полный путь к самому этому Python-скрипту.
SCRIPT_PATH = Path(__file__).resolve()

# Получаем каталог, в котором находится сам скрипт.
# Именно от этого каталога начнётся рекурсивный обход проекта.
ROOT_DIR = SCRIPT_PATH.parent

# Указываем имя итогового текстового файла.
OUTPUT_FILE = ROOT_DIR / "ALL_SITE_FILES.txt"


# Эта функция пытается определить, является ли файл текстовым.
def read_text_file(file_path: Path):

    # Сначала читаем файл как набор байтов.
    data = file_path.read_bytes()

    # Нулевые байты почти всегда означают бинарный файл:
    # изображение, архив, исполняемый файл, шрифт и т. п.
    if b"\x00" in data:
        return None

    # Перечисляем наиболее вероятные кодировки файлов проекта.
    encodings = [
        "utf-8",
        "utf-8-sig",
        "cp1251",
        "utf-16",
    ]

    # Последовательно пробуем каждую кодировку.
    for encoding in encodings:

        # Пытаемся преобразовать байты файла в обычный текст.
        try:

            # Если декодирование успешно — возвращаем содержимое файла.
            return data.decode(encoding)

        # Если эта кодировка не подошла — пробуем следующую.
        except UnicodeDecodeError:
            pass

    # Если ни одна кодировка не подошла, считаем файл бинарным.
    return None


# Открываем итоговый TXT-файл на запись.
# UTF-8 позволяет без проблем сохранять русский текст.
with OUTPUT_FILE.open("w", encoding="utf-8") as output:

    # Рекурсивно получаем вообще все объекты внутри каталога проекта.
    # Символ "*" означает любые имена файлов и каталогов.
    for file_path in sorted(ROOT_DIR.rglob("*")):

        # Пропускаем каталоги, потому что нас интересуют только файлы.
        if not file_path.is_file():
            continue

        # Не добавляем итоговый ALL_SITE_FILES.txt внутрь самого себя.
        if file_path.resolve() == OUTPUT_FILE.resolve():
            continue

        # Получаем путь файла относительно корня проекта.
        # Например: assets/css/style.css вместо полного C:\Users\...\style.css.
        relative_path = file_path.relative_to(ROOT_DIR)

        # Записываем хорошо заметный разделитель перед каждым файлом.
        output.write("\n\n")

        # Записываем путь к очередному файлу.
        output.write("=" * 100 + "\n")

        # Записываем имя и относительный путь файла.
        output.write(f"FILE: {relative_path}\n")

        # Ещё раз записываем разделитель.
        output.write("=" * 100 + "\n\n")

        # Пытаемся прочитать содержимое файла как текст.
        try:

            # Передаём файл нашей функции определения текстового содержимого.
            text = read_text_file(file_path)

            # Если функция вернула None, файл оказался бинарным.
            if text is None:

                # В таком случае сам бинарный мусор в TXT не записываем.
                # Но имя файла сохраняем, поэтому структура проекта не теряется.
                output.write("[БИНАРНЫЙ ФАЙЛ — СОДЕРЖИМОЕ НЕ ВКЛЮЧЕНО]\n")

            # Если файл оказался текстовым, записываем его полностью.
            else:

                # Записываем исходный код или другое текстовое содержимое файла.
                output.write(text)

                # Добавляем перевод строки после содержимого файла.
                output.write("\n")

        # Если какой-либо файл невозможно прочитать из-за прав доступа
        # или другой системной ошибки, скрипт не прекращает работу.
        except Exception as error:

            # Вместо содержимого записываем описание возникшей ошибки.
            output.write(f"[ОШИБКА ЧТЕНИЯ: {error}]\n")


# После завершения выводим в консоль путь к созданному файлу.
print(f"Готово: {OUTPUT_FILE}")